# -*- coding: utf-8 -*-
"""Sound-only 4 x 4 pad presets for KeyDeck.

Page metadata identifies a performance bank; the normal key sound/action fields remain
the source of truth so pads keep working after ordinary Studio edits and layout sharing.
"""

from __future__ import annotations

from calendar_app.infrastructure.i18n import t
from calendar_app.shared.beatmaker_sound_catalog import (
    BEATMAKER_DRUMS,
    BEATMAKER_NOTES,
)

BEATMAKER_TEMPLATE_ID = "beatmaker_4x4"
BEATMAKER_TEMPLATE_KITS = {
    BEATMAKER_TEMPLATE_ID: "lofi",
    "beatmaker_neon_4x4": "neon",
    "beatmaker_arcade_4x4": "arcade",
}
BEATMAKER_SHORTCUTS = "1234QWERASDFZXCV"
BEATMAKER_KITS = (
    ("lofi", "beatmaker.kit_lofi", "Lo-fi Desk"),
    ("neon", "beatmaker.kit_neon", "Neon Beat"),
    ("arcade", "beatmaker.kit_arcade", "8-bit Arcade"),
)
BEATMAKER_BANKS = (
    ("drums", "beatmaker.bank_drums", "드럼"),
    ("melody", "beatmaker.bank_melody", "멜로디"),
)
_KIT_IDS = frozenset(item[0] for item in BEATMAKER_KITS)
_BANK_IDS = frozenset(item[0] for item in BEATMAKER_BANKS)
_DRUM_COLORS = (
    "#ad8bff",
    "#a79cff",
    "#74d6bf",
    "#cf88f4",
    "#74cbb5",
    "#75d8c6",
    "#80e3d9",
    "#7dbff1",
    "#eed173",
    "#f0df8f",
    "#d5b789",
    "#c9d887",
    "#ee9968",
    "#ed7b83",
    "#e797bb",
    "#eac2a0",
)
_NOTE_COLORS = ("#86cdb6", "#7ac9dc", "#93b4ed", "#b69fe9", "#daa5d2")


def beatmaker_state(page: object) -> dict | None:
    """Return validated bank metadata, or None for an ordinary launcher page."""
    if not isinstance(page, dict):
        return None
    raw = page.get("beatmaker")
    if not isinstance(raw, dict):
        return None
    kit, bank = raw.get("kit"), raw.get("bank")
    if (
        not isinstance(kit, str)
        or kit not in _KIT_IDS
        or not isinstance(bank, str)
        or bank not in _BANK_IDS
    ):
        return None
    return {"kit": kit, "bank": bank}


def beatmaker_keys(kit: str = "lofi", bank: str = "drums") -> list[dict]:
    """Build sixteen playable pads, ordered left-to-right and top-to-bottom."""
    from calendar_app.presentation.widgets.keydeck.model import default_key

    kit = kit if kit in _KIT_IDS else "lofi"
    bank = bank if bank in _BANK_IDS else "drums"
    if bank == "drums":
        voices = [
            (voice, str(t(f"beatmaker.voice_{voice}", label))) for voice, label in BEATMAKER_DRUMS
        ]
    else:
        # Pitched pads rise from the bottom left, like a musical pad controller.
        voices = [
            (voice, label)
            for row in range(3, -1, -1)
            for voice, label, _midi in BEATMAKER_NOTES[row * 4 : row * 4 + 4]
        ]
    keys = []
    for index, (voice, label) in enumerate(voices):
        key = default_key()
        # A musical grid uses large, flat pads with a quiet secondary shortcut legend.
        key.update(
            {
                "x": float(index % 4),
                "y": float(index // 4),
                "label": label,
                "sublabel": BEATMAKER_SHORTCUTS[index],
                "action": {"type": "sound", "target": "", "paste": False},
                "sound": f"beat_{kit}_{voice}",
                "switch": "silent",
            }
        )
        color = _DRUM_COLORS[index] if bank == "drums" else _NOTE_COLORS[index % 5]
        key["cap"].update({"material": "solid", "profile": "flat", "color": color})
        key["insert"]["kind"] = "none"
        key["legend"].update(
            {
                "layout": "center",
                "glyph": "none",
                "size": 90,
                "color": "#18212f",
                "shadow": False,
            }
        )
        key["led"].update({"mode": "reactive", "color": color})
        keys.append(key)
    return keys


def apply_beatmaker_preset(
    deck: dict, kit: str = "lofi", bank: str = "drums", page_index: int | None = None
) -> dict:
    """Replace one bank in place, preserving the page identity and other deck pages.

    Replacing the pads is a deliberate preset operation; normal key edits remain normal
    key edits and are not regenerated by normalization or by changing deck themes.
    """
    kit = kit if kit in _KIT_IDS else "lofi"
    bank = bank if bank in _BANK_IDS else "drums"
    index = int(deck.get("page", 0)) if page_index is None else int(page_index)
    page = deck["pages"][index]
    page["beatmaker"] = {"kit": kit, "bank": bank}
    fallback = "비트메이커 · 드럼" if bank == "drums" else "비트메이커 · 멜로디"
    page["name"] = str(t(f"beatmaker.page_{bank}", fallback))[:24]
    page["keys"] = beatmaker_keys(kit, bank)
    return deck


